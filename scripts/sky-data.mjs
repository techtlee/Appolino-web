// Builds the hero's sky from its sources: node scripts/sky-data.mjs
//
// - Stars: d3-celestial's Hipparcos stars to magnitude 6 (BSD-3-Clause,
//   github.com/ofrohn/d3-celestial) - every star to magnitude 5.2 is kept in
//   the field, a figure's stars too: a screen too narrow for the figures
//   still has every bright star.
// - Constellations: Stellarium's "western" sky culture, each figure's lines
//   (github.com/Stellarium/stellarium-skycultures).
// - Drawings: James Hedberg's constellation art for OpenSpace, CC BY 4.0,
//   placed and prepared by sky-art.mjs into public/sky/; the site credits
//   them in its footer, as the licence requires.
// - Star names: d3-celestial's starnames.json, for each figure's brightest star.
//
// Writes src/components/skyData.ts; nothing in it is edited by hand.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { drawings } from "./sky-art.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const STEL = "https://raw.githubusercontent.com/Stellarium/stellarium-skycultures/master/western/";
const D3 = "https://raw.githubusercontent.com/ofrohn/d3-celestial/master/data/";
/** The faintest star kept: 6.0, about what the eye sees on a truly dark night
 *  (some 2 500 stars above the horizon at once). 5.2 was a suburban sky. */
const MAG_LIMIT = 6.0;

/** Figures taken whole - their lines from Stellarium, their drawing from
 *  OpenSpace - with what each is called in English and in Czech: every one
 *  the owner named. A spacing rule once left eight of them out, when the
 *  owner found the sky crowded; the crowding came from lines and drawings
 *  shown at rest, and at rest a figure is now only its stars, a drawing
 *  shows one at a time, so all of them are back (the owner, 2026-11-01). */
const NAMES = {
  Tau: ["Taurus", "Býk"],
  Gem: ["Gemini", "Blíženci"],
  Aur: ["Auriga", "Vozka"],
  CMa: ["Canis Major", "Velký pes"],
  Boo: ["Boötes", "Pastýř"],
  Vir: ["Virgo", "Panna"],
  Lyr: ["Lyra", "Lyra"],
  Aql: ["Aquila", "Orel"],
  Sco: ["Scorpius", "Štír"],
  Sgr: ["Sagittarius", "Střelec"],
  Peg: ["Pegasus", "Pegas"],
  And: ["Andromeda", "Andromeda"],
  Per: ["Perseus", "Perseus"],
};

/** Figures whose drawing alone is taken, to be shown over the hero's own
 *  shapes (heroField.ts, ASTERISMS) - the Big Dipper is drawn, the whole
 *  Great Bear pictured. */
const ART = ["UMa", "UMi", "Cas", "Ori", "Leo", "Cyg"];

const get = async (url) => {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
};
const r2 = (v, d) => +v.toFixed(d);

const [culture, stars, names] = await Promise.all([get(STEL + "index.json"), get(D3 + "stars.6.json"), get(D3 + "starnames.json")]);

const hip = new Map();
for (const f of stars.features) {
  const [lon, dec] = f.geometry.coordinates;
  hip.set(f.id, { ra: (lon + 360) % 360, dec, mag: f.properties.mag, bv: parseFloat(f.properties.bv) || 0.6 });
}

// The folder holds exactly the drawings shown: emptied, then filled.
const sky = join(root, "public", "sky");
rmSync(sky, { recursive: true, force: true });
mkdirSync(sky, { recursive: true });
const art = await drawings([...ART, ...Object.keys(NAMES)], sky);

const figures = [];
for (const c of culture.constellations) {
  const id = String(c.id).split(" ").pop();
  if (!NAMES[id]) continue;
  const index = new Map();
  const list = [];
  const at = (h) => {
    if (!hip.has(h)) return -1;
    if (!index.has(h)) {
      index.set(h, list.length);
      list.push(h);
    }
    return index.get(h);
  };
  const lines = [];
  for (const poly of c.lines) {
    const ids = poly.filter((x) => typeof x === "number");
    for (let k = 1; k < ids.length; k++) {
      const a = at(ids[k - 1]);
      const b = at(ids[k]);
      if (a >= 0 && b >= 0) lines.push(a, b);
    }
  }
  if (!list.length) continue;
  const brightest = list.reduce((b, h) => (hip.get(h).mag < hip.get(b).mag ? h : b), list[0]);
  const nm = names[String(brightest)] ?? {};
  figures.push({
    id,
    name: NAMES[id][0],
    sub: NAMES[id][1],
    bright: [nm.bayer ? `${nm.bayer} ${id}` : `HIP ${brightest}`, nm.name || ""].filter(Boolean),
    stars: list.flatMap((h) => {
      const s = hip.get(h);
      return [r2(s.ra, 4), r2(s.dec, 4), r2(s.mag, 2), r2(s.bv, 2)];
    }),
    lines,
    art: art[id],
  });
  console.log(`${id}: ${list.length} stars, ${lines.length / 2} lines`);
}
const missing = Object.keys(NAMES).filter((id) => !figures.some((f) => f.id === id));
if (missing.length) throw new Error(`no lines for ${missing.join(", ")}`);

const field = [];
for (const s of hip.values()) if (s.mag <= MAG_LIMIT) field.push(r2(s.ra, 2), r2(s.dec, 2), r2(s.mag, 1), r2(s.bv, 1));

const out = `/* Generated by scripts/sky-data.mjs - do not edit by hand.
 * Stars: Hipparcos, via d3-celestial (BSD-3-Clause). Figures: Stellarium's
 * "western" sky culture. Drawings: James Hedberg's constellation art for
 * OpenSpace, CC BY 4.0, adapted (public/sky/). */

/** A figure of the sky: its stars (right ascension and declination in
 *  degrees, magnitude, B-V colour, four numbers each), its lines as pairs of
 *  star indices, and its drawing, w x h pixels, pinned to the sky by a mesh
 *  of anchors - cols + 1 to a row, each the image's pixel and the sky's
 *  position there, four numbers each. */
export type SkyFigure = {
  id: string;
  name: string;
  sub: string;
  bright: string[];
  stars: number[];
  lines: number[];
  art: { file: string; w: number; h: number; cols: number; anchors: number[] };
};

/** Every star to magnitude ${MAG_LIMIT}: right ascension, declination, magnitude, B-V. */
export const FIELD: number[] = ${JSON.stringify(field)};

/** Figures taken whole: lines, stars and drawing. */
export const SKY: SkyFigure[] = ${JSON.stringify(figures)};

/** Drawings shown over the hero's own shapes, by figure id. */
export const ART: Record<string, SkyFigure["art"]> = ${JSON.stringify(Object.fromEntries(ART.map((id) => [id, art[id]])))};
`;
writeFileSync(join(root, "src", "components", "skyData.ts"), out);
console.log(`${figures.length} figures, ${Object.keys(art).length} drawings, ${field.length / 4} field stars, skyData.ts ${Math.round(out.length / 1024)} KB`);
